export default function SocialLinks({ links }: { links: SocialLink[] }) {
  if (!links.length) return null;

  return (
    <ul className={styles.list}>
      {links.map((link) => (
        <li key={link.id}>
          <a
            className={styles.icon}
            href={link.url}
            target="_blank"
            /*
              `noopener` is not optional on a `_blank` link: without it the page
              that opens gets a handle on this one through `window.opener`.
              These URLs are typed by a tenant admin, so they are the last place
              to take that on trust.
            */
            rel="noopener noreferrer me"
            /* The footer shows icons only, so the name has to live here. */
            aria-label={link.label}
            title={link.label}
          >
            <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
              <path fill="currentColor" d={ICONS[link.platform] ?? ICONS.link} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
